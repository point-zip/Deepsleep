export const renameSession = (id: string, title: string) => {
  if (get().importingHistory || deletingSessions.has(id)) {
    return
  }
  const controller = getStreamController(id)
  if (controller) {
    titleRequests.delete(controller)
  }
  if (getSession(id)) {
    updateSession(id, (session) => ({ ...session, title }))
    persist(id)
  } else {
    set((state) => ({
      sessions: state.sessions.map((session) =>
        session.id === id ? { ...session, title } : session
      ),
    }))
    void db.renameSession(id, title).catch(db.reportStorageError('rename session'))
  }
}

/**
 * 删除会话；本地原件仅在没有其他会话引用时清理。远端文件不删：导入、编辑、重新生成都会复用同一个附件，
 * 同一服务端文件可能被多个会话引用，不维护引用计数。
 */
export const removeSession = (id: string): Promise<boolean> => {
  const task = removeSessionData(id).finally(() => deletionTasks.delete(task))
  deletionTasks.add(task)
  return task
}

const removeSessionData = async (id: string): Promise<boolean> => {
  if (get().importingHistory || deletingSessions.has(id)) {
    return false
  }
  const epoch = historyEpoch
  deletingSessions.add(id)
  try {
    getStreamController(id)?.abort()
    // 等本会话的流收尾，避免删除之后又被收尾保存写回来。
    await waitForIdle(id)
    if (epoch !== historyEpoch) {
      return false
    }
    await db.deleteSession(id)
    // 删除成功后登记删除时间，其他设备同步时会据此删除同一会话
    recordTombstone(id)
    if (epoch !== historyEpoch) {
      return true
    }
    sessionLoads.delete(id)
    sessionAccess.delete(id)
    unsavedSessions.delete(id)
    pendingFiles.delete(id)
    remoteSessionIds.delete(id)
    clearDraft(id)
    set((state) => ({
      sessions: state.sessions.filter((session) => session.id !== id),
      remoteSessions: [...remoteSessionIds],
      sessionCache: Object.fromEntries(
        Object.entries(state.sessionCache).filter(([key]) => key !== id)
      ),
      sessionLoadErrors: Object.fromEntries(
        Object.entries(state.sessionLoadErrors).filter(([key]) => key !== id)
      ),
      sessionSaveErrors: Object.fromEntries(
        Object.entries(state.sessionSaveErrors).filter(([key]) => key !== id)
      ),
      activeId: state.activeId === id ? null : state.activeId,
    }))
    return true
  } catch (error) {
    db.reportStorageError('delete session')(error)
    return false
  } finally {
    deletingSessions.delete(id)
    // 删除失败时保留会话，并保存停止生成后的最新状态。
    if (getSession(id)) {
      if (get().importingHistory) {
        unsavedSessions.add(id)
      } else {
        persist(id)
      }
    }
  }
}

export const stopReply = (sessionId: string) => getStreamController(sessionId)?.abort()

/**
 * 提交指定会话的最新草稿；null 表示新建会话。
 * 同步接收成功才清空草稿，附件原件由会话接管；保存失败仍通过保存入口重试。
 */
export const sendMessage = (targetSessionId: string | null) => {
  if (get().importingHistory || !get().ready) {
    return false
  }
  const prepared = prepareDraftMessage(getDraft(targetSessionId), useUploads.getState().tasks)
  if (!prepared) {
    return false
  }
  const { text, files } = prepared
  const now = Date.now()
  let sessionId = targetSessionId
  if (
    sessionId !== null &&
    (deletingSessions.has(sessionId) || getStreamController(sessionId) || !getSession(sessionId))
  ) {
    return false
  }
  if (sessionId === null) {
    const session: Session = {
      id: createId(),
      title: '',
      createdAt: now,
      updatedAt: now,
      messages: [],
      rootMessageId: null,
    }
    sessionId = session.id
    touchSession(session.id)
    set((state) => ({
      sessions: [toSessionSummary(session), ...state.sessions],
      sessionCache: { ...state.sessionCache, [session.id]: session },
      activeId: session.id,
    }))
  }
  const current = getSession(sessionId)
  if (!current) {
    return false
  }
  const history = getVisibleMessages(current)
  const question: UserMessage = {
    id: createId(),
    role: 'user',
    content: text,
    files: files.map(({ id, serverId, name, size, isImage, mimeType }) => ({
      id,
      serverId,
      // Files API 上传前会检查长边；内联供应商不留上传副本。
      imageSizeChecked: isImage && serverId !== null,
      name,
      size,
      isImage,
      mimeType,
    })),
    createdAt: now,
  }
  const reply = createReply()
  updateSession(sessionId, (session) => ({
    ...appendBranch(session, history.at(-1)?.id ?? null, [question, reply]),
    updatedAt: now,
  }))
  if (files.length > 0) {
    pendingFiles.set(sessionId, [
      ...(pendingFiles.get(sessionId) ?? []),
      ...files.map(({ id, blob }) => ({ id, blob })),
    ])
  }
  persist(sessionId)
  clearSentDraft(targetSessionId)
  void streamReply(sessionId, reply, { history, question })
  return true
}

/** 重新生成当前路径上的回答：在原问题下新增版本，不覆盖旧回答和后续对话。 */
export const regenerateReply = (sessionId: string, messageId?: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return
  }
  const path = getVisibleMessages(session)
  const index =
    messageId === undefined ? path.length - 1 : path.findIndex((m) => m.id === messageId)
  const question = path[index - 1]
  if (question?.role !== 'user' || path[index]?.role !== 'assistant') {
    return
  }
  const history = path.slice(0, index - 1)
  const reply = createReply()
  updateSession(sessionId, (s) => ({
    ...appendBranch(s, question.id, [reply]),
    updatedAt: Date.now(),
  }))
  persist(sessionId)
  void streamReply(sessionId, reply, { history, question })
}

/** 编辑提问后新增同父版本，保留原文件；旧问题的所有回答与后续对话仍可切回。 */
export const editMessage = (sessionId: string, messageId: string, content: string): boolean => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return false
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return false
  }
  const path = getVisibleMessages(session)
  const index = path.findIndex((message) => message.id === messageId)
  const previous = path[index]
  const text = content.trim()
  if (previous?.role !== 'user' || (!text && previous.files.length === 0)) {
    return false
  }
  const question: UserMessage = {
    id: createId(),
    role: 'user',
    content: text,
    files: previous.files,
    createdAt: Date.now(),
  }
  const reply = createReply()
  updateSession(sessionId, (s) => ({
    ...appendBranch(s, path[index - 1]?.id ?? null, [question, reply]),
    updatedAt: Date.now(),
  }))
  persist(sessionId)
  void streamReply(sessionId, reply, { history: path.slice(0, index), question })
  return true
}

export const selectMessageVersion = (sessionId: string, messageId: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  if (getStreamController(sessionId)) {
    return
  }
  updateSession(sessionId, (session) => selectVersion(session, messageId))
  persist(sessionId)
}

/** 继续最后一条未完成的回答：保留原消息与开关，仅将新流的内容追加到原块之后。 */
export const continueReply = (sessionId: string, messageId: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return
  }
  const path = getVisibleMessages(session)
  const question = path.at(-2)
  const previous = path.at(-1)
  if (
    question?.role !== 'user' ||
    previous?.role !== 'assistant' ||
    previous.id !== messageId ||
    !canContinueReply(previous)
  ) {
    return
  }
  const { thinking, search } = useSettings.getState()
  const reply: AssistantMessage = {
    ...previous,
    // 未记录请求配置的回复，续写时使用当前选中的模型和开关。
    model: previous.model ?? getActiveProvider()?.model ?? null,
    thinking: previous.thinking ?? thinking,
    search: previous.search ?? search,
    status: 'pending',
    stopReason: undefined,
    stopDetails: undefined,
    error: undefined,
  }
  updateReply(sessionId, reply)
  updateSession(sessionId, (s) => ({ ...s, updatedAt: Date.now() }))
  persist(sessionId)
  void streamReply(sessionId, reply, { history: path.slice(0, -2), question, prefix: previous })
}

/** 附件补传失败后重试：保留原回答位置，重新补传并请求 */
export const retryUpload = (sessionId: string, messageId: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return
  }
  const path = getVisibleMessages(session)
  const index = path.findIndex((message) => message.id === messageId)
  const question = path[index - 1]
  const previous = path[index]
  if (
    question?.role !== 'user' ||
    previous?.role !== 'assistant' ||
    previous.error?.kind !== 'upload'
  ) {
    return
  }
  const reply: AssistantMessage = { ...previous, status: 'pending', error: undefined }
  updateReply(sessionId, reply)
  persist(sessionId)
  void streamReply(sessionId, reply, { history: path.slice(0, index - 1), question })
}

type Request = { history: Message[]; question: UserMessage; prefix?: AssistantMessage }

/**
 * 将 serverId 写回所有引用同一附件的消息。传入 null 会清除超限旧图的 ID，触发补传。
 * 尺寸标记随有效 ID 保存，因为本地保留的是原图，刷新后可以直接复用已检查的上传副本。
 */
const saveServerIds = (sessionId: string, serverIds: ReadonlyMap<string, string | null>) => {
  if (serverIds.size === 0) {
    return
  }
  updateSession(sessionId, (session) => ({
    ...session,
    messages: session.messages.map((message) =>
      message.role === 'user' && message.files.some((file) => serverIds.has(file.id))
        ? {
            ...message,
            files: message.files.map((file) => {
              const serverId = serverIds.get(file.id)
              return serverId === undefined
                ? file
                : { ...file, serverId, imageSizeChecked: file.isImage && serverId !== null }
            }),
          }
        : message
    ),
  }))
  persist(sessionId)
}

/**
 * 附件的服务端 id：已有直接用；正在上传的等待同一任务；否则读取本地原件补传。
 * 本地也没有原件（导入的文档附件只有元数据）时返回 null，该附件在内联供应商下被跳过。
 */
const ensureServerId = async (
  provider: ProviderConfig,
  file: FileAttachment
): Promise<string | null> => {
  if (file.serverId) {
    return file.serverId
  }
  const task = useUploads.getState().tasks[file.id]
  if (task?.status === 'done' && task.serverId) {
    return task.serverId
  }
  const blob = await db.loadFile(file.id)
  if (!blob) {
    return null
  }
  return uploadAttachment(provider, file.id, blob, file.name, file.isImage)
}

/** 用会话里的最新消息替换请求快照：重传前会重置附件的 serverId，快照必须跟着更新 */
const refreshRequest = (sessionId: string, request: Request): Request => {
  const session = getSession(sessionId)
  if (!session) {
    return request
  }
  const byId = new Map(session.messages.map((message) => [message.id, message]))
  const pick = <T extends Message>(message: T): T =>
    (byId.get(message.id) as T | undefined) ?? message
  return {
    history: request.history.map(pick),
    question: pick(request.question),
    prefix: request.prefix,
  }
}

/**
 * 发送前补齐附件的 serverId。
 * - 本轮提问的附件并行补齐，任一失败则整体失败，已成功的照常写回，重试时复用成功结果；
 * - 历史轮次（仅进入上下文的）中没有 serverId 的附件，多为导入的图片：从最新的消息往前逐张补传，
 *   失败静默跳过，该附件不进入本次请求，下次发送时再试。
 */
const prepareFiles = async (
  sessionId: string,
  request: Request,
  signal: AbortSignal,
  provider: ProviderConfig
) => {
  // 不支持 Files API 的供应商随请求内联附件，不需要预先上传。
  if (getProviderFeatures(provider).files !== 'api') {
    return request
  }
  const epoch = historyEpoch
  // 服务端判定 file_id 失效时会清掉会话里的 serverId，先用最新消息替换请求快照，
  // 否则快照里仍是旧 id，补传会直接复用它。
  request = refreshRequest(sessionId, request)
  const serverIds = new Map<string, string>()
  // 停止生成立即生效；上传本身不取消（输入框与其他消息可能共用同一任务），完成后照常写回 serverId
  const aborted = new Promise<never>((_, reject) => {
    signal.addEventListener('abort', () => reject(signal.reason), { once: true })
  })
  // 旧图片超限时先清除 ID，交给下方已有的附件补传流程。
  const files = [
    ...request.question.files,
    ...getContextRounds(request.history).flatMap(([user]) => user.files),
  ]
  const checked = await Promise.race([checkImageFileIds(files, signal), aborted])
  if (checked.size > 0) {
    saveServerIds(sessionId, checked)
    request = refreshRequest(sessionId, request)
  }
  const uploads = Promise.allSettled(
    request.question.files.map(async (file) => {
      const serverId = await ensureServerId(provider, file)
      if (serverId && serverId !== file.serverId) {
        serverIds.set(file.id, serverId)
      }
    })
  )
  void uploads.then(() => {
    if (epoch === historyEpoch) {
      saveServerIds(sessionId, serverIds)
    }
  })
  const results = await Promise.race([uploads, aborted])
  const failed = results.find((result) => result.status === 'rejected')
  if (failed) {
    throw failed.reason
  }

  const pending = new Map<string, FileAttachment>()
  for (const [user] of getContextRounds(request.history).toReversed()) {
    for (const file of user.files) {
      if (!file.serverId && !serverIds.has(file.id) && !pending.has(file.id)) {
        pending.set(file.id, file)
      }
    }
  }
  for (const file of pending.values()) {
    signal.throwIfAborted()
    try {
      const serverId = await Promise.race([ensureServerId(provider, file), aborted])
      if (serverId) {
        serverIds.set(file.id, serverId)
        saveServerIds(sessionId, new Map([[file.id, serverId]]))
      }
    } catch {
      signal.throwIfAborted()
    }
  }

  // 用补齐后的会话重新取历史与提问，保证请求里都是 serverId
  const session = getSession(sessionId)
  const resolve = <T extends Message>(message: T): T =>
    (session?.messages.find((m) => m.id === message.id) as T | undefined) ?? message
  return {
    history: request.history.map(resolve),
    question: resolve(request.question),
    prefix: request.prefix,
  }
}

/** 本次请求实际会用到的服务端 file_id */
const collectServerFileIds = (request: Request): Set<string> => {
  const ids = new Set<string>()
  const add = (files: FileAttachment[]) => {
    for (const file of files) {
      if (file.serverId) {
        ids.add(file.serverId)
      }
    }
  }
  add(request.question.files)
  for (const [user] of getContextRounds(request.history)) {
    add(user.files)
  }
  return ids
}

/**
 * 服务端判定 file_id 失效时，清掉对应附件的 serverId 并丢弃旧的上传任务，
 * 下一次补齐会重新读取本地原件上传。报错里点名了 file_id 就只重置这些，
 * 没点名（如 invalid file_id）则重置本次请求用到的全部附件。
 */
const reuploadInvalidatedFiles = (sessionId: string, request: Request, error: unknown): boolean => {
  if (!(error instanceof ApiError) || !getFileErrorCode(error)) {
    return false
  }
  const mentioned = extractFileIds(error.message)
  // 重试时原始快照里还是上一轮已被清掉的 serverId，先换成会话里的最新消息
  const targets =
    mentioned.length > 0
      ? new Set(mentioned)
      : collectServerFileIds(refreshRequest(sessionId, request))
  const session = getSession(sessionId)
  if (targets.size === 0 || !session) {
    return false
  }
  const localIds: string[] = []
  const messages = session.messages.map((message) => {
    if (message.role !== 'user') {
      return message
    }
    let changed = false
    const files = message.files.map((file) => {
      if (!file.serverId || !targets.has(file.serverId)) {
        return file
      }
      localIds.push(file.id)
      changed = true
      return { ...file, serverId: null }
    })
    return changed ? { ...message, files } : message
  })
  if (localIds.length === 0) {
    return false
  }
  updateSession(sessionId, (current) => ({ ...current, messages }))
  // 上传任务里可能还留着同一个失效的 serverId，清掉后 ensureServerId 才会重新上传
  localIds.forEach(cancelUpload)
  persist(sessionId)
  return true
}

/** 重传前的退避等待；停止生成时立即返回，由调用方按已停止收尾 */
const waitForRetry = (attempt: number, signal: AbortSignal) =>
  new Promise<void>((resolve) => {
    function onAbort() {
      clearTimeout(timer)
      resolve()
    }
    const timer = setTimeout(
      () => {
        signal.removeEventListener('abort', onAbort)
        resolve()
      },
      FILE_RETRY_BASE_DELAY * 2 ** attempt
    )
    signal.addEventListener('abort', onAbort, { once: true })
  })

/**
 * 请求并消费流：先补齐附件的 serverId，再发请求；流式增量按动画帧刷新内存，完成、失败或停止后落盘。
 * 补传失败时回复记为 upload 错误，可重试。
 * 服务端判定 file_id 失效时重新补传后重发，退避重试且次数有上限，超过则按原始报错收尾。
 */
const streamReply = async (sessionId: string, initial: AssistantMessage, request: Request) => {
  const controller = new AbortController()
  if (!getSession(sessionId)?.title) {
    titleRequests.add(controller)
  }
  set((state) => ({ streaming: { ...state.streaming, [sessionId]: controller } }))
  let reply = initial
  let frame = 0
  const flush = () => {
    cancelAnimationFrame(frame)
    frame = 0
    updateReply(sessionId, reply)
  }
  streamFlushes.set(sessionId, flush)

  try {
    const provider = getActiveProvider()
    if (!isProviderUsable(provider)) {
      reply = settleReply(reply, 'error', Date.now(), {
        kind: 'http',
        message: '',
        localMessage: { key: 'replyNoProvider' },
      })
      return
    }
    const features = getProviderFeatures(provider)
    const adapter = getAdapter(provider.protocol)
    for (let attempt = 0; ; attempt += 1) {
      /** 附件补齐前出错属于上传失败，请求还没有发出 */
      let preparing = true
      let receivedContent = false
      try {
        const prepared = await prepareFiles(sessionId, request, controller.signal, provider)
        preparing = false
        // 附件就绪后获取本轮信息；续写沿用原回答快照，重新生成的快照独立保存。
        const latestReminder = prepared.prefix
          ? prepared.prefix.latestReminder
          : createLatestReminder(useSettings.getState())
        reply = { ...reply, latestReminder }
        updateReply(sessionId, reply)
        persist(sessionId)
        // 供应商没有服务端工具时，由「工具服务」在客户端完成搜索、抓取与 OCR
        const serverTools = getProviderExtensions(provider).deepseek
        const toolsEndpoint = serverTools ? null : getToolsEndpoint()
        // 标准协议已声明服务端搜索时不再做客户端预搜索，避免同一轮重复搜索
        const clientSearch = (initial.search ?? false) && !features.search
        const documents =
          features.files === 'api' || !toolsEndpoint
            ? []
            : prepared.question.files.filter((file) => !file.isImage)
        const clientRun =
          toolsEndpoint &&
          (clientSearch ||
            documents.length > 0 ||
            extractUrls(prepared.question.content).length > 0)
            ? await runClientTools({
                endpoint: toolsEndpoint,
                question: prepared.question,
                search: clientSearch,
                documents,
                signal: controller.signal,
              })
            : null
        const messages = toRequestMessages(
          prepared.history,
          prepared.question,
          prepared.prefix,
          initial.thinking ?? false,
          latestReminder,
          clientRun?.context
        )
        const chat: ChatRequest = {
          model: initial.model ?? provider.model,
          system: SYSTEM_PROMPT,
          messages,
          thinking: initial.thinking ?? false,
          thinkingLevel: useSettings.getState().thinkingLevel,
          // 服务端搜索只在供应商支持时下发；客户端搜索已在上方完成
          search: (initial.search ?? false) && features.search,
          title: features.title && titleRequests.has(controller),
        }
        const events = (async function* () {
          if (clientRun) {
            yield* clientRun.events
          }
          yield* adapter.stream({
            provider,
            features,
            deepseek: serverTools,
            request: chat,
            loadAttachment,
            signal: controller.signal,
          })
        })()
        const blockIndexes = new Map<number, number>()
        for await (const event of events) {
          receivedContent ||= event.type === 'content_block_start'
          if (
            event.type === 'message_delta' &&
            (event.delta.stop_reason === 'end_turn' || event.delta.stop_reason === 'max_tokens') &&
            event.delta.title?.trim() &&
            titleRequests.has(controller) &&
            !controller.signal.aborted &&
            !get().importingHistory
          ) {
            const title = event.delta.title.trim()
            updateSession(sessionId, (session) => (session.title ? session : { ...session, title }))
            titleRequests.delete(controller)
          }
          reply = applyEvent(reply, event, Date.now(), blockIndexes)
          if (document.visibilityState === 'hidden') {
            flush()
          } else {
            frame ||= requestAnimationFrame(flush)
          }
        }
        reply = settleReply(reply, 'done', Date.now())
        // 服务端没有给出标题（或供应商不支持）时，用首条提问的摘要补标题。
        if (titleRequests.has(controller) && !controller.signal.aborted) {
          const title = titleFromQuestion(prepared.question.content)
          if (title && !get().importingHistory) {
            updateSession(sessionId, (session) => (session.title ? session : { ...session, title }))
          }
          titleRequests.delete(controller)
        }
        break
      } catch (error) {
        if (controller.signal.aborted) {
          reply = settleReply(reply, 'stopped', Date.now())
          break
        }
        if (preparing) {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: 'upload',
            message: '',
            localMessage: describeUploadError(error),
            retryable: isRetryableApiError(error),
          })
          break
        }
        // 附件失效：重新补传后重发。收到过内容块（含丢弃的客户端工具）后不自动重发。
        if (
          attempt < FILE_RETRY_LIMIT &&
          !receivedContent &&
          reuploadInvalidatedFiles(sessionId, request, error)
        ) {
          await waitForRetry(attempt, controller.signal)
          if (controller.signal.aborted) {
            reply = settleReply(reply, 'stopped', Date.now())
            break
          }
          continue
        }
        if (error instanceof ApiError && error.kind === 'interrupted' && reply.stopReason) {
          // 已收到 message_delta 的结束原因，只是缺了结尾的 message_stop
          reply = settleReply(reply, 'done', Date.now())
        } else if (error instanceof ApiError) {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: error.kind,
            message: error.message,
            status: error.status,
            localMessage: error.localMessage,
          })
        } else {
          reply = settleReply(reply, 'error', Date.now(), {
            kind: 'protocol',
            message: error instanceof Error ? error.message : String(error),
          })
        }
        break
      }
    }
  } finally {
    titleRequests.delete(controller)
    streamFlushes.delete(sessionId)
    cancelAnimationFrame(frame)
    updateReply(sessionId, reply)
    set((state) => ({
      streaming: Object.fromEntries(
        Object.entries(state.streaming).filter(([id]) => id !== sessionId)
      ),
    }))
    persist(sessionId)
    requestSync()
  }
}

/** 等尚未落盘的会话写完，避免同步写入被正在进行的保存覆盖 */
const waitForSaves = () =>
  new Promise<void>((resolve) => {
    if (unsavedSessions.size === 0) {
      resolve()
      return
    }
    const started = Date.now()
    const timer = setInterval(() => {
      if (unsavedSessions.size === 0 || Date.now() - started > 5000) {
        clearInterval(timer)
        resolve()
      }
    }, 50)
  })

/** 同步读取全部会话：已加载的用内存里的最新版本，未加载的逐条从本地库读取 */
export const collectSessions = async (): Promise<Session[]> => {
  const { sessions, sessionCache } = get()
  const result: Session[] = []
  for (const summary of sessions) {
    // 远端未下载的占位项没有正文，不读本地库
    if (isRemoteSession(summary.id)) {
      continue
    }
    const session = Object.hasOwn(sessionCache, summary.id)
      ? sessionCache[summary.id]
      : await db.loadSession(summary.id)
    if (session) {
      result.push({ ...session, ...summary })
    }
  }
  return result
}

/** 当前列表里的全部摘要，含远端未下载的占位项 */
export const collectSessionSummaries = (): SessionSummary[] => get().sessions

/** 清单里的最新摘要：本次下载的优先，其次内存里的最新版本 */
const latestSummary = (
  summary: SessionSummary,
  downloaded: Map<string, Session>
): SessionSummary => {
  const session = downloaded.get(summary.id) ?? getSession(summary.id)
  return session ? toSessionSummary(session) : summary
}

/**
 * 更新列表与详情缓存：写入本次下载的会话、移除已删除的会话；
 * 清单里没有但同步期间新建的本地会话继续保留，避免正在进行的对话从列表消失。
 */
const applyManifestState = (
  manifestSessions: SessionSummary[],
  removed: Set<string>,
  downloaded: Map<string, Session>,
  extra: SessionSummary[]
) => {
  const known = new Set(manifestSessions.map((summary) => summary.id))
  const summaries = manifestSessions
    .filter((summary) => !removed.has(summary.id))
    .map((summary) => latestSummary(summary, downloaded))
  for (const summary of extra) {
    if (!known.has(summary.id) && !removed.has(summary.id)) {
      summaries.push(summary)
    }
  }
  for (const id of removed) {
    sessionAccess.delete(id)
    unsavedSessions.delete(id)
    pendingFiles.delete(id)
  }
  const withoutRemoved = (source: Record<string, boolean>) =>
    Object.fromEntries(Object.entries(source).filter(([id]) => !removed.has(id)))
  set((state) => {
    const sessionCache: Record<string, Session> = {}
    for (const [id, session] of Object.entries(state.sessionCache)) {
      if (removed.has(id)) {
        continue
      }
      sessionCache[id] = downloaded.get(id) ?? session
    }
    for (const [id, session] of downloaded) {
      if (!Object.hasOwn(sessionCache, id)) {
        sessionCache[id] = session
      }
    }
    return {
      sessions: sortSessions(summaries),
      sessionCache,
      sessionLoadErrors: withoutRemoved(state.sessionLoadErrors),
      sessionSaveErrors: withoutRemoved(state.sessionSaveErrors),
      activeId: state.activeId !== null && removed.has(state.activeId) ? null : state.activeId,
    }
  })
  trimSessionCache()
}

/**
 * 应用同步清单：更新会话列表（含远端未下载的占位项），写入本次下载的会话与图片原件，
 * 删除其他设备已删除的会话。只有真正写库时才复用导入锁停止生成；
 * 只改动受影响的会话，当前打开的会话与草稿尽量保留。
 */
export const applySyncedManifest = async (
  manifestSessions: SessionSummary[],
  removed: string[],
  remoteOnly: readonly string[],
  downloaded: Session[] = [],
  files: db.StoredFile[] = []
): Promise<void> => {
  const removeIds = new Set(removed)
  const downloadedById = new Map(downloaded.map((session) => [session.id, session]))
  // 清单里没有、但同步期间新建的本地会话：确认有正文后继续保留
  const known = new Set(manifestSessions.map((summary) => summary.id))
  const extra: SessionSummary[] = []
  for (const summary of get().sessions) {
    if (known.has(summary.id) || removeIds.has(summary.id)) {
      continue
    }
    if (getSession(summary.id) || (await db.loadSession(summary.id).catch(() => undefined))) {
      extra.push(summary)
    }
  }
  replaceRemoteSessions(remoteOnly)
  if (removeIds.size === 0 && downloadedById.size === 0 && files.length === 0) {
    // 只调整列表与未下载标记，不打断正在生成的回答
    applyManifestState(manifestSessions, removeIds, downloadedById, extra)
    return
  }
  if (get().importingHistory) {
    throw new SyncError('busy')
  }
  set({ importingHistory: true })
  try {
    for (const controller of Object.values(get().streaming)) {
      controller.abort()
    }
    await Promise.all(deletionTasks)
    await waitForIdle()
    await waitForSaves()
    historyEpoch += 1
    sessionLoads.clear()
    for (const id of removeIds) {
      await db.deleteSession(id)
      clearDraft(id)
    }
    if (files.length > 0) {
      await db.saveFiles(files)
    }
    for (const session of downloaded) {
      await db.saveSession(session)
    }
    applyManifestState(manifestSessions, removeIds, downloadedById, extra)
  } finally {
    set({ importingHistory: false })
    retrySaveSessions()
    const { activeId } = get()
    if (activeId !== null && !getSession(activeId)) {
      void ensureSessionLoaded(activeId)
    }
  }
}

/** 单个远端会话下载完成：清掉未下载标记，刷新列表摘要与已加载的详情 */
export const noteSessionDownloaded = (session: Session) => {
  remoteSessionIds.delete(session.id)
  publishRemoteSessions()
  const summary = toSessionSummary(session)
  set((state) => ({
    sessions: sortSessions(
      state.sessions.some((item) => item.id === session.id)
        ? state.sessions.map((item) => (item.id === session.id ? summary : item))
        : [...state.sessions, summary]
    ),
    // 已经打开的会话直接放入详情缓存，避免并发同步打断这次读取后一直停在加载中
    sessionCache:
      Object.hasOwn(state.sessionCache, session.id) || state.activeId === session.id
        ? { ...state.sessionCache, [session.id]: session }
        : state.sessionCache,
    sessionLoadErrors: Object.fromEntries(
      Object.entries(state.sessionLoadErrors).filter(([id]) => id !== session.id)
    ),
  }))
}
